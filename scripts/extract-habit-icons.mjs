/**
 * Extracts every icon listed in src/features/habits/icons/catalog.ts from
 * Iconify (the open icon library behind icones.js.org) and bundles the SVG
 * markup into src/features/habits/icons/icon-svgs.generated.ts. The app then
 * draws them locally, so it stays fully offline.
 *
 *   node scripts/extract-habit-icons.mjs
 *
 * Re-run after adding or removing icons in the catalog. Needs Node 22.18+ /
 * 23.6+, which can import the TypeScript catalog directly.
 */
import { Buffer } from 'node:buffer';
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { EMOJI_ICONS, ICON_SETS, LINE_ICONS } from '../src/features/habits/icons/catalog.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FILE = join(ROOT, 'src/features/habits/icons/icon-svgs.generated.ts');
const API = 'https://api.iconify.design';

// react-native-svg can't draw these; refuse the icon rather than ship a broken glyph.
const UNSUPPORTED = /<(filter|foreignObject|style|animate\w*|script|image)\b/;

async function fetchCollection(prefix, names) {
  const url = `${API}/${prefix}.json?icons=${names.join(',')}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} responded ${response.status}`);

  const data = await response.json();
  if (data.not_found?.length) {
    throw new Error(`Not found in "${prefix}": ${data.not_found.join(', ')}`);
  }
  return data;
}

function toSvg(data, name) {
  const aliasParent = data.aliases?.[name]?.parent;
  const icon = data.icons?.[name] ?? (aliasParent ? data.icons?.[aliasParent] : undefined);
  if (!icon) throw new Error(`"${name}" missing from the "${data.prefix}" response`);
  if (UNSUPPORTED.test(icon.body)) throw new Error(`"${data.prefix}:${name}" uses SVG features react-native-svg can't draw`);

  const left = icon.left ?? data.left ?? 0;
  const top = icon.top ?? data.top ?? 0;
  const width = icon.width ?? data.width ?? 16;
  const height = icon.height ?? data.height ?? 16;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${left} ${top} ${width} ${height}">${icon.body}</svg>`;
}

async function extract(kind, defs) {
  const prefix = ICON_SETS[kind];
  const data = await fetchCollection(prefix, defs.map((def) => def.source));
  return defs.map((def) => [def.id, toSvg(data, def.source)]);
}

async function main() {
  const all = [...LINE_ICONS, ...EMOJI_ICONS];
  const duplicates = all.map((def) => def.id).filter((id, index, ids) => ids.indexOf(id) !== index);
  if (duplicates.length) throw new Error(`Duplicate icon ids in the catalog: ${duplicates.join(', ')}`);

  const entries = [...(await extract('line', LINE_ICONS)), ...(await extract('emoji', EMOJI_ICONS))];

  const body = entries.map(([id, svg]) => `  ${JSON.stringify(id)}: ${JSON.stringify(svg)},`).join('\n');
  const source = `// Generated by scripts/extract-habit-icons.mjs from Iconify. Do not edit by hand.
// Line icons: Tabler Icons, MIT License, https://tabler.io/icons
// Emoji: Microsoft Fluent Emoji (Flat), MIT License, https://github.com/microsoft/fluentui-emoji

/** Complete SVG markup for each habit icon, keyed by id (\`line:run\`, \`emoji:droplet\`). */
export const ICON_SVGS: Record<string, string> = {
${body}
};
`;

  await writeFile(OUT_FILE, source, 'utf8');
  const kb = (Buffer.byteLength(source) / 1024).toFixed(1);
  console.log(`Wrote ${entries.length} icons (${LINE_ICONS.length} line, ${EMOJI_ICONS.length} emoji), ${kb} KB`);
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
